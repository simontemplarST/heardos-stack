"""Render the kit's plan file (heardos.env) from the installer's plan dict, for the laptop copy and the host copy.

The kit sources this file with `set -a`, so every value must be a valid shell assignment. Secrets that the kit needs
on the host (CF token is NOT one of them; Authentik token is) are passed in explicitly by the step that writes the file.
"""
from __future__ import annotations

import shlex
from pathlib import Path
from typing import Any, Mapping

PLAN_KEYS = [
    "DOMAIN", "ACME_EMAIL", "TZ", "ADMIN_USER", "ADMIN_EMAIL", "ADMIN_NAME", "BRAND_TITLE", "PUBLIC_HOSTS",
    "HOST_LAN_IP", "LAN_SUBNET", "LAN_DOMAIN", "HEARDOS_ROOT", "HOST_OVERLAY",
    "NEBULA_LH_IP", "NEBULA_LH_OVERLAY", "OVERLAY_CIDR", "LAPTOP_OVERLAY",
    "CF_ZONE_ID", "PORTAINER_URL", "AUTHENTIK_URL", "IMMICH_SERVER_CPUS", "IMMICH_ML_CPUS", "OCR_LANGS", "OCR_CPUS",
    "PROXY_SUBNET", "CADDY_FRONT_DOOR", "BRAND_PRIMARY", "BRAND_COLOR",
    # 2026-10-19 security review: fixed Traefik address (header trust), shared media group, opt-in LAN http redirects,
    # CrowdSec home allowlist, pinned Nebula, SSH over the overlay once the lighthouse is locked
    "PROXY_IP_RANGE", "TRAEFIK_PROXY_IP", "MEDIA_GID", "LAN_HTTP", "HOME_PUBLIC_IP", "NEBULA_VERSION", "NEBULA_LH_SSH",
    # per-install image choices (an adopted install keeps the database engines it runs; see docs/adopt-and-migrate.md)
    "AUTHENTIK_PG_IMAGE", "PAPERLESS_PG_IMAGE", "LISTMONK_PG_IMAGE", "IMMICH_DB_IMAGE", "NEXTCLOUD_PG_IMAGE", "OLLAMA_CPUS", "KIWIX_ZIM",
    "AUTHENTIK_API_BIND", "HA_HOST_NETWORK", "HA_DEVICE", "CHAT_HARNESS_URL",
]
SECRET_KEYS_BY_SIDE = {
    "local": ["CF_API_TOKEN", "AUTHENTIK_TOKEN", "PORTAINER_TOKEN"],
    "host": ["AUTHENTIK_TOKEN", "PORTAINER_TOKEN", "HA_TOKEN", "RESTIC_REPOSITORY", "RESTIC_PASSWORD"]   # mail secrets go to 43 as env only,
}


def _val(v: Any) -> str:
    if isinstance(v, (list, tuple)):
        v = " ".join(str(x) for x in v)
    if isinstance(v, bool):
        v = "1" if v else ""
    return shlex.quote(str(v)) if v is not None else "''"


def render_plan(plan: Mapping[str, Any], secrets: Mapping[str, str], side: str) -> str:
    lines = [f"# heardos.env ({side}) — generated by the HeardOS installer; do not edit by hand, re-run the installer instead."]
    for k in PLAN_KEYS:
        if k in plan and plan[k] not in (None, ""):
            lines.append(f"{k}={_val(plan[k])}")
    for k in SECRET_KEYS_BY_SIDE[side]:
        if secrets.get(k):
            lines.append(f"{k}={_val(secrets[k])}")
    return "\n".join(lines) + "\n"


def write_plan(path: Path, plan: Mapping[str, Any], secrets: Mapping[str, str], side: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_plan(plan, secrets, side))
    path.chmod(0o600)
    return path
