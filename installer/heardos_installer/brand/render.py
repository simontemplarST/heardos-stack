"""Build the brand bundle the installer uploads: /srv/heardos-brand on the VPS (emails link to cloud.<domain>/brand/...)
and Authentik's media/public/branding + templates/email on the home server.

  out/
    files/        logo-dark.png logo-light.png mark-*.png favicon-*.png favicon.ico apple-touch-icon.png app-icon-*.png
                  flow-background.jpg custom.css
    email/        Authentik email templates with the palette, name and domain filled in

With no logo the HeardOS artwork is used when the title is HeardOS, otherwise a monogram mark and a wordmark are drawn.
"""
from __future__ import annotations

import math
import re
import shutil
from pathlib import Path
from typing import Optional

from ..kit.locate import kit_path
from .theme import DEFAULT_PRIMARY, Palette, derive

DEFAULT_TITLE = "HeardOS"


def _font(size: int, bold: bool = True):
    """Inter ships with the kit (brand/fonts, OFL) so a wordmark looks the same on every operator OS."""
    from PIL import ImageFont
    try:
        return ImageFont.truetype(str(kit_path("brand", "fonts", "Inter-Bold.ttf" if bold else "Inter-SemiBold.ttf")), size)
    except OSError:
        return ImageFont.load_default(size=size)


def initials(title: str) -> str:
    words = [w for w in re.findall(r"[A-Za-z0-9]+", title) if w.lower() not in {"the", "family", "cloud", "of", "and", "s"}]
    return (words[0][0] if words else (title[:1] or "H")).upper()


def monogram(pal: Palette, letter: str, size: int = 512, tile: bool = True):
    """Rounded square in the accent colour with the family initial (tile=False: the letter alone, for watermarks)."""
    from PIL import Image, ImageDraw
    s4 = size * 4
    im = Image.new("RGBA", (s4, s4), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    if tile:
        d.rounded_rectangle([0, 0, s4 - 1, s4 - 1], radius=int(s4 * 0.22), fill=pal.rgb("primary"))
    f = _font(int(s4 * 0.62))
    box = d.textbbox((0, 0), letter, font=f)
    d.text(((s4 - (box[2] - box[0])) / 2 - box[0], (s4 - (box[3] - box[1])) / 2 - box[1]), letter, font=f, fill=pal.rgb("on_primary") if tile else (255, 255, 255))
    return im.resize((size, size), Image.LANCZOS)


def wordmark(pal: Palette, mark, title: str, on_dark: bool, height: int = 512):
    from PIL import Image, ImageDraw
    f = _font(int(height * 0.42))
    tmp = ImageDraw.Draw(Image.new("RGBA", (1, 1)))
    box = tmp.textbbox((0, 0), title, font=f)
    gap = int(height * 0.18)
    w = height + gap + (box[2] - box[0]) + int(height * 0.08)
    im = Image.new("RGBA", (w, height), (0, 0, 0, 0))
    im.paste(mark.resize((height, height)), (0, 0), mark.resize((height, height)))
    color = pal.rgb("text_light") if on_dark else pal.rgb("ink")
    ImageDraw.Draw(im).text((height + gap - box[0], (height - (box[3] - box[1])) / 2 - box[1]), title, font=f, fill=color)
    return im


def _square(im, size: int):
    from PIL import Image
    im = im.convert("RGBA")
    side = max(im.size)
    canvas = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    canvas.paste(im, ((side - im.width) // 2, (side - im.height) // 2))
    return canvas.resize((size, size), Image.LANCZOS)


def background(pal: Palette, mark, out: Path, W: int = 2560, H: int = 1440) -> None:
    """Sign-in background: charcoal-to-ink vignette, accent glow lower right, faint mark watermark, fine grid."""
    from PIL import Image, ImageChops, ImageDraw

    def field(fn, w=320, h=180):
        im = Image.new("L", (w, h)); px = im.load()
        for y in range(h):
            for x in range(w):
                px[x, y] = max(0, min(255, int(fn(x / (w - 1), y / (h - 1)) * 255)))
        return im.resize((W, H), Image.BICUBIC)

    vig = field(lambda u, v: 1 - min(1, ((u - 0.5) ** 2 / 0.45 + (v - 0.5) ** 2 / 0.55)) ** 1.1)
    glow = field(lambda u, v: 0.34 * max(0, 1 - math.sqrt(((u - 0.78) / 0.55) ** 2 + ((v - 0.86) / 0.6) ** 2)) ** 2.2)
    base = Image.composite(Image.new("RGB", (W, H), pal.rgb("charcoal")), Image.new("RGB", (W, H), pal.rgb("ink")), vig)
    base = Image.composite(Image.new("RGB", (W, H), pal.rgb("primary")), base, glow)
    s = int(H * 1.05)
    m = mark.convert("RGBA").resize((s, s), Image.LANCZOS)
    alpha = ImageChops.multiply(m.convert("L"), m.split()[3]).point(lambda v: int(v * 0.075))
    base.paste(Image.new("RGB", m.size, pal.rgb("text_light")), (int(W * 0.60), int(H * 0.5 - s * 0.47)), alpha)
    grid = Image.new("L", (W, H), 0); g = ImageDraw.Draw(grid)
    for x in range(0, W, 96):
        g.line([(x, 0), (x, H)], fill=255)
    for y in range(0, H, 96):
        g.line([(0, y), (W, y)], fill=255)
    base = Image.composite(Image.new("RGB", (W, H), (0x4e, 0x4e, 0x54)), base, grid.point(lambda v: int(v * 0.035)))
    base.save(out, quality=88, optimize=True, subsampling=0)


def custom_css(pal: Palette) -> str:
    return f"""/* Generated by the HeardOS installer (brand/render.py). Accent {pal.primary}; charcoal neutrals. */
:root, :root.pf-theme-dark, .pf-c-page, ak-flow-executor, .pf-c-login {{
  --pf-global--primary-color--100: {pal.primary};
  --pf-global--primary-color--200: {pal.deep};
  --pf-global--primary-color--light-100: {pal.light};
  --pf-global--primary-color--dark-100: {pal.deep};
  --pf-global--link--Color: {pal.deep};
  --pf-global--link--Color--hover: {pal.primary};
  --pf-global--active-color--100: {pal.primary};
  --pf-global--BorderColor--100: #4e4e54;
  --pf-global--FontFamily--sans-serif: Inter, "Segoe UI", Roboto, sans-serif;
}}
.pf-c-button.pf-m-primary {{ background-color: {pal.primary}; color: {pal.on_primary}; font-weight: 600; }}
.pf-c-button.pf-m-primary:hover, .pf-c-button.pf-m-primary:focus {{ background-color: {pal.light}; color: {pal.on_primary}; }}
.pf-c-login__main {{ border-top: 4px solid {pal.primary}; border-radius: 6px; }}
.pf-c-brand {{ max-height: 72px; }}
.pf-c-login__footer, .pf-c-login__header {{ color: #c9c9cf; }}
"""


def render_emails(pal: Palette, title: str, domain: str, out: Path) -> int:
    src = kit_path("authentik", "email-templates", "email")
    out.mkdir(parents=True, exist_ok=True)
    n = 0
    for f in sorted(src.iterdir()):
        if f.suffix not in (".html", ".txt"):
            continue
        t = f.read_text()
        t = t.replace("color:#1f2023 !important", f"color:{pal.on_primary} !important")   # button label on the accent
        for old, new in (("#f2a35e", pal.primary), ("#ed8325", pal.deep), ("#f5b984", pal.light)):
            t = re.sub(re.escape(old), new, t, flags=re.I)
        t = t.replace("example.com", domain).replace(DEFAULT_TITLE, title)
        (out / f.name).write_text(t)
        n += 1
    return n


def build(out: Path, *, title: str = DEFAULT_TITLE, primary: str = DEFAULT_PRIMARY, domain: str,
          logo: Optional[Path] = None) -> Palette:
    from PIL import Image
    pal = derive(primary)
    files = out / "files"
    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(kit_path("brand", "heardos"), files)
    custom_art = bool(logo) or title != DEFAULT_TITLE
    watermark = None
    if custom_art:
        if logo:
            src = Image.open(logo).convert("RGBA")
            mark = _square(src, 512)
            ratio = src.width / src.height
            logo_dark = logo_light = src.resize((max(1, round(512 * ratio)), 512), Image.LANCZOS) if ratio > 1.4 else wordmark(pal, mark, title, True)
            if ratio <= 1.4:
                logo_light = wordmark(pal, mark, title, False)
        else:
            mark = monogram(pal, initials(title))
            watermark = monogram(pal, initials(title), tile=False)
            logo_dark, logo_light = wordmark(pal, mark, title, True), wordmark(pal, mark, title, False)
        logo_dark.save(files / "logo-dark.png"); logo_light.save(files / "logo-light.png")
        for f in ("logo-dark.svg", "logo-light.svg", "favicon.svg", "logo-stacked-dark.png", "logo-stacked-light.png"):
            (files / f).unlink(missing_ok=True)           # HeardOS-only artwork; the PNGs above replace them
        for name in ("mark-dark", "mark-light"):
            mark.save(files / f"{name}.png"); mark.resize((128, 128), Image.LANCZOS).save(files / f"{name}-128.png")
        for s in (16, 32, 64):
            mark.resize((s, s), Image.LANCZOS).save(files / f"favicon-{s}.png")
        mark.resize((180, 180), Image.LANCZOS).save(files / "apple-touch-icon.png")
        for s in (192, 512):
            mark.resize((s, s), Image.LANCZOS).save(files / f"app-icon-{s}.png")
        mark.save(files / "favicon.ico", sizes=[(16, 16), (32, 32), (48, 48)])
    else:
        mark = Image.open(files / "mark-dark.png")
    if custom_art or pal.primary != DEFAULT_PRIMARY:
        background(pal, watermark or mark, files / "flow-background.jpg")
    (files / "custom.css").write_text(custom_css(pal))
    render_emails(pal, title, domain, out / "email")
    return pal
