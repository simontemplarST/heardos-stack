#!/usr/bin/env python3
"""homepage-config.py OUTDIR — write the family hub's Homepage config (settings/services/widgets/bookmarks) from catalog.json.

Only apps that are installed on this host get a tile (a stack is installed when $HEARDOS_ROOT/stacks/<stack>/compose.yml
exists), so re-running after each 50-app.sh keeps the hub in step. Tiles link to the front door cloud.<domain>/<slug>.
Env: DOMAIN, HEARDOS_ROOT, BRAND_TITLE (default HeardOS), BRAND_COLOR (a Homepage colour name, default orange). stdlib only.
"""
import json, os, sys
from pathlib import Path

here = Path(__file__).resolve().parent.parent
out = Path(sys.argv[1]); out.mkdir(parents=True, exist_ok=True)
dom, root = os.environ["DOMAIN"], Path(os.environ.get("HEARDOS_ROOT", "/opt/heardos"))
title, color = os.environ.get("BRAND_TITLE") or "HeardOS", os.environ.get("BRAND_COLOR") or "orange"
cat = json.loads((here / "catalog.json").read_text())
ORDER = ["Everyday", "House & paperwork", "Account"]


def q(s):  # YAML double-quoted scalar
    return json.dumps(s, ensure_ascii=False)


def installed(stack):
    return (root / "stacks" / stack / "compose.yml").is_file()


groups = {g: [] for g in ORDER}
for a in cat["apps"]:
    h = a.get("hub")
    if not h or not installed(a["stack"]):
        continue
    href = f"https://cloud.{dom}/{a['slug']}" if a.get("slug") else f"https://{a['hosts'][0]}.{dom}/"
    groups.setdefault(h["group"], []).append((h["label"], h["icon"], href, h["description"]))
groups["Account"].insert(0, ("My account", "authentik.png", f"https://auth.{dom}/if/user/", "Change password, add a passkey, sign out"))

svc = ["# Generated by lib/homepage-config.py from catalog.json; re-run 50-app.sh homepage to refresh. Edits here are overwritten."]
for g, tiles in groups.items():
    if not tiles:
        continue
    svc.append(f"- {q(g)}:")
    for label, icon, href, desc in tiles:
        svc += [f"    - {q(label)}:", f"        icon: {icon}", f"        href: {href}", f"        description: {q(desc)}"]
if (out / "services.yaml").exists() and "heardos: keep" in (out / "services.yaml").read_text():
    print("services.yaml: hand-curated (heardos: keep), left alone")
else:
    (out / "services.yaml").write_text("\n".join(svc) + "\n")

layout = "".join(f"  {q(g)}:\n    style: row\n    columns: 4\n" for g, t in groups.items() if t)
(out / "settings.yaml").write_text(f"""# Generated by lib/homepage-config.py. Big labelled tiles, no status dots, no widgets that need keys.
title: {q(title)}
favicon: https://cloud.{dom}/brand/favicon-32.png
description: Our family apps
theme: dark
color: {color}
headerStyle: boxed
language: en
target: _self
hideVersion: true
disableUpdateCheck: true
statusStyle: ""
showStats: false
quicklaunch:
  searchDescriptions: true
  hideInternetSearch: true
  hideVisitURL: true
layout:
{layout}""")
(out / "widgets.yaml").write_text("- greeting:\n    text_size: 2xl\n    text: " + q(title) + "\n- datetime:\n    text_size: l\n    format:\n      dateStyle: long\n      timeStyle: short\n")
for f in ("bookmarks.yaml", "docker.yaml", "kubernetes.yaml", "custom.css", "custom.js"):
    p = out / f
    if not p.exists():
        p.write_text("[]\n" if f == "bookmarks.yaml" else "")
print(f"hub config: {sum(len(t) for t in groups.values())} tiles in {out}")
